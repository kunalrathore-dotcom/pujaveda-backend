async function seed() {
  await mongoose.connect(process.env.MONGODB_URI);
  console.log('Connected to MongoDB Atlas...');
  const catCol = mongoose.connection.collection('categories');
  const prodCol = mongoose.connection.collection('products');

  const categories = await catCol.find({}).toArray();
  const catMap = new Map();
  for (const c of categories) {
    catMap.set(c.slug, c);
  }

  for (const item of SAMPLE_PRODUCTS) {
    const parentCat = catMap.get(item.categorySlug);
    if (!parentCat) {
      console.warn('Category not found for slug:', item.categorySlug);
      continue;
    }

    const subcategoryObj = parentCat.subcategories?.find(s => s.slug === item.subcategorySlug);

    const doc = {
      name: item.name,
      slug: item.slug,
      sku: item.sku,
      category: parentCat._id,
      subcategory: subcategoryObj ? subcategoryObj._id : undefined,
      price: item.price,
      originalPrice: item.originalPrice,
      stock: item.countInStock,
      countInStock: item.countInStock,
      isPublished: item.isPublished,
      isFeatured: item.isFeatured,
      shortDescription: item.shortDescription,
      description: item.description,
      material: item.material,
      weight: item.weight,
      dimensions: item.dimensions,
      packContents: item.packContents,
      origin: item.origin,
      idealFor: item.idealFor,
      careInstructions: item.careInstructions,
      tags: item.tags,
      image: item.images[0],
      images: item.images,
      primaryImage: item.images[0],
      ratings: {
        average: 0,
        count: 0
      },
      updatedAt: new Date()
    };

    await prodCol.updateOne(
      { slug: item.slug },
      {
        $set: doc,
        $setOnInsert: {
          createdAt: new Date(),
          reviews: []
        }
      },
      { upsert: true }
    );
    console.log(`Upserted product: ${item.name} (${item.sku})`);
  }

  const count = await prodCol.countDocuments({});
  console.log('Total products now in database:', count);
  process.exit(0);
}

seed().catch(err => {
  console.error(err);
  process.exit(1);
});
